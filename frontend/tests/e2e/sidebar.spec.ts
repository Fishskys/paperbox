import { expandNavigation, expect, test } from "./fixtures";
import { contrastFailures } from "./contrast";

for (const theme of ["light", "dark"]) {
  test(`desktop navigation folds groups and keeps workspace controls in place in ${theme}`, async ({ page }, testInfo) => {
    await page.addInitScript(value => localStorage.setItem("paperbox:theme", value), theme);
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.route("**/api/papers?*", route => route.fulfill({ json: { total: 0, papers: [] } }));
    await page.goto("/search");
    const sidebar = page.locator(".sidebar");
    const groups = sidebar.locator(".nav-group-title");
    await expect(groups).toHaveCount(5);
    expect(await groups.evaluateAll(items => items.every(item => item.getAttribute("aria-expanded") === "false"))).toBe(true);
    await expect(sidebar.locator(".nav-item:visible")).toHaveCount(0);
    await expect(sidebar.locator(".nav-dot")).toHaveCount(0);
    await expect(sidebar.locator(".nav-group-items").first()).toHaveAttribute("inert", "");
    await expect(page.getByText("个人研究空间", { exact: true })).toHaveCount(0);
    const settings = page.locator(".topbar").getByRole("button", { name: "连接与外观设置" });
    const connection = page.locator(".topbar .connection");
    await expect(connection).toHaveText("API 已连接");
    await expect(settings).toBeVisible();
    const statusBox = (await connection.boundingBox())!;
    const settingsBox = (await settings.boundingBox())!;
    expect(settingsBox.x).toBeGreaterThanOrEqual(statusBox.x + statusBox.width);
    expect(settingsBox.x).toBeGreaterThan(1200);
    await expect(sidebar.locator(".connection")).toHaveCount(0);
    await expect(page.locator(".topbar .desktop-toggle")).toHaveCount(0);

    const search = sidebar.getByRole("button", { name: "检索", exact: true });
    await search.focus(); await page.keyboard.press("Enter");
    await expect(search).toHaveAttribute("aria-expanded", "true");
    await sidebar.getByRole("link", { name: "常规检索", exact: true }).click();
    await expect(page.getByRole("heading", { name: "常规检索", exact: true })).toBeVisible();
    await expandNavigation(page, "导入");
    await expandNavigation(page, "系统管理");
    const collapse = sidebar.getByRole("button", { name: "收起侧栏", exact: true });
    await expect(collapse.locator("svg")).toHaveClass(/lucide-panel-left/);
    const box = (await collapse.boundingBox())!;
    expect(box.x).toBeLessThan(50);
    expect(box.y).toBeGreaterThan(820);
    await collapse.click();
    await expect(page.locator(".workspace")).toHaveClass(/sidebar-collapsed/);
    await expect(sidebar.locator(".nav-item:visible")).toHaveCount(0);
    await expect(sidebar.locator(".nav-group-label:visible")).toHaveCount(0);
    await expect(sidebar.locator(".nav-group-chevron:visible")).toHaveCount(0);
    expect(await groups.evaluateAll(items => items.every(item => item.getAttribute("aria-expanded") === "false"))).toBe(true);
    await sidebar.getByRole("button", { name: "阅读", exact: true }).hover();
    await expect(page.getByRole("tooltip", { name: "阅读", exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("collapsed.png"), fullPage: true });
    await sidebar.getByRole("button", { name: "导入", exact: true }).click();
    await expect(page.locator(".workspace")).not.toHaveClass(/sidebar-collapsed/);
    await expect(sidebar.getByRole("link", { name: "元数据导入", exact: true })).toBeVisible();
    await expect(search).toHaveAttribute("aria-expanded", "false");
    await sidebar.getByRole("button", { name: "收起侧栏", exact: true }).click();
    await sidebar.getByRole("button", { name: "展开侧栏", exact: true }).click();
    await expect(sidebar.locator(".nav-item:visible")).toHaveCount(0);
    await page.screenshot({ path: testInfo.outputPath("expanded.png"), fullPage: true });
    await page.addStyleTag({ content: "*,*::before,*::after{transition:none!important;animation:none!important}" });
    expect(await contrastFailures(page)).toEqual([]);
    await page.reload();
    await expect(sidebar.locator(".nav-item:visible")).toHaveCount(0);
  });

  test(`mobile navigation remains complete after desktop collapse in ${theme}`, async ({ page }, testInfo) => {
    await page.addInitScript(value => localStorage.setItem("paperbox:theme", value), theme);
    await page.goto("/search");
    await page.locator(".sidebar").getByRole("button", { name: "收起侧栏", exact: true }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    const settings = page.locator(".topbar").getByRole("button", { name: "连接与外观设置" });
    await expect(settings).toBeVisible();
    await settings.click();
    await expect(page.getByRole("dialog", { name: "连接与外观", exact: true })).toBeVisible();
    await page.getByRole("button", { name: /^取\s*消$/ }).click();
    await page.getByRole("button", { name: "打开导航", exact: true }).click();
    const drawer = page.getByRole("dialog", { name: "Paperbox", exact: true });
    await expect(drawer.locator(".nav-group-label:visible")).toHaveCount(5);
    await expect(drawer.locator(".nav-item:visible")).toHaveCount(0);
    await expandNavigation(page, "导入", drawer);
    await expect(drawer.getByRole("link", { name: "元数据导入", exact: true })).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath("mobile-navigation.png"), fullPage: true });
    await drawer.getByRole("link", { name: "元数据导入", exact: true }).click();
    await expect(drawer).not.toBeVisible();
    await expect(page.getByRole("heading", { name: "元数据导入", exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath("mobile-topbar.png"), fullPage: true });
    await page.addStyleTag({ content: "*,*::before,*::after{transition:none!important;animation:none!important}" });
    expect(await contrastFailures(page)).toEqual([]);
    await page.setViewportSize({ width: 1440, height: 900 });
    await expect(page.locator(".workspace")).toHaveClass(/sidebar-collapsed/);
    await expect(page.locator(".sidebar .nav-item:visible")).toHaveCount(0);
  });
}

test("navigation animates height and width and respects reduced motion", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.goto("/search");
  const sidebar = page.locator(".sidebar");
  await expect(sidebar.locator(".nav-group-title")).toHaveCount(5);
  await expandNavigation(page, "检索");
  const menu = sidebar.locator(".nav-group-items").first();
  await expect(menu).not.toHaveAttribute("inert");
  expect(await menu.evaluate(el => getComputedStyle(el).transitionDuration)).toContain("0.22s");
  await sidebar.getByRole("button", { name: "收起侧栏", exact: true }).click();
  expect(await page.locator(".workspace").evaluate(el => el.getAnimations().some(animation =>
    animation instanceof CSSTransition && animation.transitionProperty === "grid-template-columns"))).toBe(true);
  await expect.poll(() => sidebar.evaluate(el => el.getBoundingClientRect().width)).toBe(64);
  await expect(menu).toHaveAttribute("inert", "");
  await page.emulateMedia({ reducedMotion: "reduce" });
  await sidebar.getByRole("button", { name: "展开侧栏", exact: true }).click();
  expect(await sidebar.evaluate(el => el.getBoundingClientRect().width)).toBe(224);
  await expandNavigation(page, "检索");
  expect(await menu.evaluate(el => getComputedStyle(el).transitionDuration)).toBe("0s");
  await expect(sidebar.getByRole("link", { name: "常规检索", exact: true })).toBeVisible();
});